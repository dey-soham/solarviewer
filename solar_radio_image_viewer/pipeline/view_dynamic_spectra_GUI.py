    # ----------------------- Undo/Redo Functionality ----------------------------

    def _apply_edit(self, edit, undo=False):
        self._mask_version += 1  # (the whole-file median is computed again)
        kind, value = edit
        if kind == "set":  # (before, after): each (masks, channels[, keeps])
            state = value[0] if undo else value[1]
            self._masks = list(state[0])
            self._global_masked_freq_indices = set(state[1])
            if len(state) > 2:
                self._keeps = list(state[2])
            return
        if kind == "keep":
            if undo:
                self._keeps.remove(value)
            else:
                self._keeps.append(value)
            return
        if kind == "add":
            if undo:
                self._masks.remove(value)
            else:
                self._masks.append(value)
        elif kind == "extend":
            if undo:
                self._global_masked_freq_indices.difference_update(value)
            else:
                self._global_masked_freq_indices.update(value)
        elif kind == "clear":
            if undo:
                self._masks = list(value[0])
                self._global_masked_freq_indices = set(value[1])
                if len(value) > 2:
                    self._keeps = list(value[2])
            else:
                self._masks = []
                self._global_masked_freq_indices = set()
                self._keeps = []

    def _do(self, edit):
        """Make a mask edit (undoable) and show the page with it."""
        self._apply_edit(edit)
        self._update_mask_summary()
        self._autosave_masks()
        self.undo_stack.append(edit)
        self.redo_stack.clear()
        self._update_undo_actions()
        self._redisplay()

    def _update_undo_actions(self):
        """Undo and Redo, greyed out when there is nothing to undo or redo."""
        self.undoAct.setEnabled(bool(self.undo_stack))
        self.redoAct.setEnabled(bool(self.redo_stack))

    def undo(self):
        if not self.undo_stack:
            self.statusBar().showMessage("Nothing to undo.", 3000)
            return
        edit = self.undo_stack.pop()
        self._select_region(None)
        self._apply_edit(edit, undo=True)
        self._update_mask_summary()
        self._autosave_masks()
        self.redo_stack.append(edit)
        self._update_undo_actions()
        self._redisplay()

    def redo(self):
        if not self.redo_stack:
            self.statusBar().showMessage("Nothing to redo.", 3000)
            return
        edit = self.redo_stack.pop()
        self._select_region(None)
        self._apply_edit(edit)
        self._update_mask_summary()
        self._autosave_masks()
        self.undo_stack.append(edit)
        self._update_undo_actions()
        self._redisplay()

    def onBandpassNorm(self, checked):
        """Toggle persistent bandpass normalization."""
        if self._shown_raw is None:
            if checked:
                self.normBtn.blockSignals(True)
                self.normBtn.setChecked(False)
                self.normBtn.blockSignals(False)
            return

        self.logger.info(f"Bandpass Normalization toggled to: {checked}")
        self._redisplay_bandpass(checked, self._bandpass_scope)

        self.statusBar().showMessage(
            f"Bandpass normalization {'enabled' if checked else 'disabled'}.", 5000
        )

    def canvas_auto_downsample(self, enabled):
        self.canvas.set_auto_downsample(enabled)

    def onBandpassScopeChanged(self, index):
        scope = self.bandpassScopeCombo.itemData(index)
        if self._is_bandpass_enabled and self._shown_raw is not None:
            self._redisplay_bandpass(True, scope)
        else:
            self._bandpass_scope = scope

    def onBandpassMethodChanged(self, index):
        method = self.bandpassMethodCombo.itemData(index)
        if self._is_bandpass_enabled and self._shown_raw is not None:
            self._redisplay_bandpass(True, self._bandpass_scope, method)
        else:
            self._bandpass_method = method

    def _apply_binning(self):
        """Show the page again averaged as the spin boxes say."""
        binning = (self.timeBinSpin.value(), self.freqBinSpin.value())
        if binning == self._bin:
            return
        self._bin = binning
        self._redisplay()
        self.statusBar().showMessage(
            f"Averaging {binning[0]} time samples × {binning[1]} channels", 5000
        )

    def _redisplay_bandpass(self, enabled, scope, method=None):
        """Show the page with bandpass normalisation ``enabled`` (the median
        over ``scope``, divided or subtracted by ``method``)."""
        self._is_bandpass_enabled = enabled
        self._bandpass_scope = scope
        if method is not None:
            self._bandpass_method = method
        # The page caches hold the data as read: redrawing is enough (a page
        # still loading is normalised when shown)
        self._redisplay()

    def _previewing(self):
        """Whether the page shown is still its quick preview (every few
        samples) while the full page loads."""
        return self._shown_raw is not None and bool(self._shown_raw[3])

