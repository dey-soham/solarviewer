    def onRoiToggled(self, checked):
        if self._original_data is None:
            QMessageBox.information(self, "Info", "No data loaded.")
            self.roiButton.setChecked(False)
            return

        try:
            if checked:
                # Mutual exclusivity: disable cross section if active
                if self.crossBtn.isChecked():
                    self.crossBtn.setChecked(False)
                if self.driftBtn.isChecked():
                    self.driftBtn.setChecked(False)
                if self.keepBtn.isChecked():
                    self.keepBtn.setChecked(False)

                self.logger.info("Enabling ROI selector...")
                self.canvas.enable_roi_selector(True, self._mask_roi_values)
                self._show_keep_boxes()
                self.statusBar().showMessage(
                    "Mask Region ON: Click and drag to select an area to mask."
                )
                self.logger.info("ROI selector enabled successfully")
            else:
                self.logger.info("Disabling ROI selector...")
                self.canvas.enable_roi_selector(False)
                self._show_keep_boxes()
                self.statusBar().clearMessage()
                self.logger.info("ROI selector disabled")
        except Exception as e:
            # Handle any exceptions and inform the user
            error_msg = f"There was an error with the ROI selector: {str(e)}"
            self.logger.exception(error_msg)
            QMessageBox.warning(
                self,
                "ROI Selection Error",
                error_msg,
            )

            # Reset button state
            self.roiButton.setChecked(False)

            # Disable the selector and clean up
            try:
                self.canvas.enable_roi_selector(False)
            except Exception as cleanup_error:
                self.logger.error(f"Error during cleanup: {cleanup_error}")

            # Update the status bar
            self.statusBar().showMessage("ROI selection disabled due to an error", 5000)

    def onCrossSectionToggled(self, checked):
        if self._original_data is None:
            QMessageBox.information(self, "Info", "No data loaded.")
            self.crossBtn.setChecked(False)
            return

        if checked:
            # Mutual exclusivity: disable ROI if active
            if self.roiButton.isChecked():
                self.roiButton.setChecked(False)
            if self.driftBtn.isChecked():
                self.driftBtn.setChecked(False)
            if self.keepBtn.isChecked():
                self.keepBtn.setChecked(False)

        self.canvas.enable_cross_section(checked)
        if checked:
            self.statusBar().showMessage("Cross-section mode ON. Click on data.")
        else:
            self.statusBar().clearMessage()

    def onDriftToggled(self, checked):
        if checked and self._original_data is None:
            QMessageBox.information(self, "Info", "No data loaded.")
            self.driftBtn.setChecked(False)
            return
        if checked:
            for other in (self.roiButton, self.keepBtn, self.crossBtn):
                if other.isChecked():
                    other.setChecked(False)
            self.statusBar().showMessage(
                "Drift rate: click the start of the burst, then its end."
            )
        else:
            self.statusBar().clearMessage()
            self.driftPanel.hide()
        self.canvas.enable_drift(checked)

    def sendTimeToViewer(self, t, f=float("nan")):
        """Ask SolarViewer (which launched this) for its image nearest time
        ``t`` (MJD seconds) and, of those, frequency ``f`` (MHz)."""
        when = datetime(1858, 11, 17) + timedelta(seconds=t)
        message = {"show_time": when.isoformat()}
        if np.isfinite(f):
            message["freq_mhz"] = f
        if not self.link.send(message):
            self.statusBar().showMessage("SolarViewer isn't running any more", 5000)
            return
        at = f", {f:.2f} MHz" if np.isfinite(f) else ""
        self.statusBar().showMessage(
            f"Asked SolarViewer for its image nearest {when:%H:%M:%S}{at}", 5000
        )

    def _on_link_message(self, message):
        """Do as SolarViewer says: open a spectrum, come to the front, take
        its theme, or close with it."""
        if "open" in message:
            self.openFile(message["open"])
        if message.get("raise"):
            if self.isMinimized():
                self.showNormal()
            self.raise_()
            self.activateWindow()
        theme = message.get("theme")
        if theme in ("dark", "light") and theme != self.current_theme:
            self.current_theme = theme
            self._applyStyle()
        if message.get("close"):
            self.close()

    def onDriftMeasured(self, t1, f1, t2, f2):
        d = drift_rate(t1, f1, t2, f2)

        def speed(v):
            return f"{v:,.0f} km/s ({v / 299792.458:.2f} c)" if v is not None else "n/a"

        text = (
            f"Δt = {d['dt']:.2f} s, Δf = {d['df']:.2f} MHz\n"
            f"Drift: {d['rate']:.3f} MHz/s\n"
            f"Fundamental: {speed(d['v_f'])}\n"
            f"Harmonic: {speed(d['v_h'])}"
        )
        self.driftLabel.setText(text)
        self._update_tool_hint()
        self.statusBar().showMessage(f"Drift: {d['rate']:.3f} MHz/s", 10000)

    def resizeEvent(self, event):
        """Handle window resize events to ensure canvas redraws properly"""
        super().resizeEvent(event)
        # Use a timer to avoid excessive redrawing during resize
        if self.resizeTimer is not None:
            self.resizeTimer.stop()

        # Wait for resize to complete before redrawing
        from PyQt5.QtCore import QTimer

        self.resizeTimer = QTimer()
        self.resizeTimer.setSingleShot(True)
        self.resizeTimer.timeout.connect(self._delayed_redraw)
        self.resizeTimer.start(200)  # 200ms delay

    def _delayed_redraw(self):
        """Redraw the canvas after resize is complete"""
        if hasattr(self, "canvas") and self.canvas._data is not None:
            self.canvas.draw_idle()


